function createOption(size: HatSize, questionIndex: number, optionIndex: number, spec: OptionSpec): HatQuestionOption {
  const [text, primary, secondary] = spec
  return {
    id: `${size}-${String(questionIndex + 1).padStart(2, '0')}-${String.fromCharCode(97 + optionIndex)}`,
    text,
    weights: secondary ? [[primary, 3], [secondary, 1]] : [[primary, 3]],
  }
}

function createQuestions(size: HatSize, optionSets: readonly OptionSet[]): readonly HatQuestion[] {
  if (optionSets.length !== SCENARIOS.length) throw new Error(`${size} option set must contain ${SCENARIOS.length} questions.`)
  return SCENARIOS.map((scenario, questionIndex) => ({
    id: `${size}-${String(questionIndex + 1).padStart(2, '0')}`,
    size,
    ...scenario,
    options: optionSets[questionIndex].map((spec, optionIndex) => createOption(size, questionIndex, optionIndex, spec)) as unknown as HatQuestion['options'],
  }))
}

