export const PIXEL_INK = {
  k: '#080808', d: '#444444', m: '#999999', w: '#f5f5f5',
  r: '#ff243b', g: '#24ff72', b: '#2864ff',
} as const

export const SPECTRUM = {
  red: 0xff243b, green: 0x24ff72, blue: 0x2864ff, yellow: 0xffee24,
  orange: 0xff7b24, magenta: 0xff24e5, cyan: 0x24edff, white: 0xffffff, dark: 0x777777,
} as const

export function spectrumColor(power: RgbPower): number {
  return SPECTRUM[visibleColor(power)]
}

export function sourceAccent(kind: DeviceKind): string {
  return kind === 'source-red' ? PIXEL_INK.r : kind === 'source-green' ? PIXEL_INK.g : kind === 'source-blue' ? PIXEL_INK.b : PIXEL_INK.w
}

