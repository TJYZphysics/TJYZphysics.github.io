export type PixelRun = { x: number; y: number; width: number; ink: string }

const runCache = new Map<readonly string[], readonly PixelRun[]>()

export function pixelRuns(rows: readonly string[]): readonly PixelRun[] {
  const cached = runCache.get(rows)
  if (cached) return cached
  const runs: PixelRun[] = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ink = row[x]
      const start = x++
      while (row[x] === ink) x++
      if (ink !== '.') runs.push({ x: start, y, width: x - start, ink })
    }
  })
  runCache.set(rows, runs)
  return runs
}
